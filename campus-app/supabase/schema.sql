-- Campus app schema for Supabase (Postgres)
-- Run once in: Supabase dashboard > SQL Editor > New query > Run

create table if not exists universities (
  id bigint generated by default as identity primary key,
  name text not null,
  city text
);

create table if not exists faculties (
  id bigint generated by default as identity primary key,
  university_id bigint not null references universities(id),
  name text not null
);

create table if not exists users (
  id bigint generated by default as identity primary key,
  name text not null,
  university_id bigint references universities(id),
  faculty_id bigint references faculties(id),
  year int,
  languages text,
  weekly_free_hours int default 0,
  is_demo boolean default false,
  allow_messages boolean default true,
  created_at timestamptz default now()
);

create table if not exists courses (
  id bigint generated by default as identity primary key,
  faculty_id bigint references faculties(id),
  code text,
  name text not null,
  teacher text,
  room text,
  schedule_text text,
  syllabus text
);

create table if not exists enrollments (
  user_id bigint references users(id) on delete cascade,
  course_id bigint references courses(id) on delete cascade,
  semester text,
  primary key (user_id, course_id)
);

create table if not exists classes (
  id bigint generated by default as identity primary key,
  course_id bigint references courses(id) on delete cascade,
  weekday int not null check (weekday between 0 and 6),
  start_time time not null,
  end_time time not null,
  room text
);

create table if not exists deadlines (
  id bigint generated by default as identity primary key,
  course_id bigint references courses(id) on delete cascade,
  title text not null,
  type text,
  due_at timestamptz not null,
  description text
);

create table if not exists availability_slots (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete cascade,
  weekday int not null check (weekday between 0 and 6),
  start_time time not null,
  end_time time not null
);

create table if not exists course_files (
  id bigint generated by default as identity primary key,
  course_id bigint references courses(id) on delete cascade,
  kind text not null check (kind in ('syllabus', 'presentation')),
  title text not null,
  url text
);

create table if not exists study_plans (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete cascade,
  created_at timestamptz default now(),
  plan_json jsonb not null,
  source text not null check (source in ('ai', 'fallback'))
);

-- Feed tables added in Phase 2D. Already applied to the live database.
create table if not exists posts (
  id bigint generated by default as identity primary key,
  author_id bigint references users(id) on delete cascade,
  university_id bigint references universities(id),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz default now(),
  hidden boolean default false
);

create table if not exists post_likes (
  post_id bigint references posts(id) on delete cascade,
  user_id bigint references users(id) on delete cascade,
  primary key (post_id, user_id)
);

create table if not exists post_reports (
  id bigint generated by default as identity primary key,
  post_id bigint references posts(id) on delete cascade,
  reporter_id bigint references users(id) on delete cascade,
  reason text not null,
  created_at timestamptz default now(),
  unique (post_id, reporter_id)
);

-- Messaging tables added in Phase 2E. Already applied to the live database.
create table if not exists conversations (
  id bigint generated by default as identity primary key,
  user_a_id bigint not null references users(id) on delete cascade,
  user_b_id bigint not null references users(id) on delete cascade,
  created_at timestamptz default now(),
  last_message_at timestamptz,
  unique (user_a_id, user_b_id),
  check (user_a_id < user_b_id)
);

create table if not exists messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references conversations(id) on delete cascade,
  sender_id bigint not null references users(id) on delete cascade,
  body text,
  deleted boolean default false,
  created_at timestamptz default now()
);

create table if not exists conversation_reads (
  conversation_id bigint not null references conversations(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  last_read_at timestamptz,
  primary key (conversation_id, user_id)
);

create table if not exists user_blocks (
  blocker_id bigint not null references users(id) on delete cascade,
  blocked_id bigint not null references users(id) on delete cascade,
  created_at timestamptz default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create table if not exists conversation_reports (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references conversations(id) on delete cascade,
  reporter_id bigint not null references users(id) on delete cascade,
  reason text not null,
  created_at timestamptz default now(),
  unique (conversation_id, reporter_id)
);

-- Security: enable Row Level Security on every table.
-- No anon policies are added, so the browser cannot read or write tables directly.
-- Netlify Functions use the service role key, which bypasses RLS on the server only.
-- When real login is added, per-student policies go here.
alter table universities enable row level security;
alter table faculties enable row level security;
alter table users enable row level security;
alter table courses enable row level security;
alter table enrollments enable row level security;
alter table classes enable row level security;
alter table deadlines enable row level security;
alter table availability_slots enable row level security;
alter table course_files enable row level security;
alter table study_plans enable row level security;
alter table posts enable row level security;
alter table post_likes enable row level security;
alter table post_reports enable row level security;
alter table conversations enable row level security;
alter table messages enable row level security;
alter table conversation_reads enable row level security;
alter table user_blocks enable row level security;
alter table conversation_reports enable row level security;

